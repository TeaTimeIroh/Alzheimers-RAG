"""
api.py - REST API for the RAG system (FastAPI).

Endpoints
  GET  /health              database, number of chunks, configured models
  GET  /search?q=...&k=5&mode=hybrid   retrieval only: the top-k chunks (no LLM call)
  POST /ask                 {"question": "...", "top_k": 5, "retrieval": "hybrid"} -> answer + sources

Search mode: vector | keyword | hybrid (see search.py); default RETRIEVAL from .env, else hybrid.
  GET  /docs                interactive Swagger UI (generated by FastAPI)

Access: /search and /ask need an API key in the X-API-Key header, with the "search" or "ask"
scope (401 without a valid key, 403 without the scope); /health and /docs are open. Create keys
with  python auth.py create <name> --scopes search,ask  (see auth.py).

The embedding model is loaded once at startup; each request opens its own short database
connection (simple and safe with FastAPI's thread pool; a connection pool would be the next step
under real load). The LLM backend is whatever .env configures (LM Studio or Gemini).

Run:  python auth.py create me
      uvicorn api:app --reload
      then open http://127.0.0.1:8000/docs, "Authorize" with the key
"""
import logging
from contextlib import asynccontextmanager
from typing import Dict, List, Literal, Optional

import psycopg
from fastapi import Depends, FastAPI, HTTPException, Query
from pgvector.psycopg import register_vector
from pydantic import BaseModel, Field

import answer                                   # loads .env; LLM client and ask()
import auth
from search import DEFAULT_MODEL, DSN, default_mode, search

STATE: Dict[str, object] = {}


@asynccontextmanager
async def lifespan(app: FastAPI):
    from sentence_transformers import SentenceTransformer
    logger = logging.getLogger("rag")
    if not logger.handlers:                       # who called what, by key name
        handler = logging.StreamHandler()
        handler.setFormatter(logging.Formatter("%(asctime)s %(levelname)s %(name)s: %(message)s"))
        logger.addHandler(handler)
        logger.setLevel(logging.INFO)
    if not auth.auth_enabled():
        logger.warning("API_AUTH is off: /search and /ask accept requests without a key")
    elif not auth.load():
        logger.warning("no API keys in %s yet - create one: python auth.py create <name>",
                       auth.keys_file())
    STATE["embed_model"] = SentenceTransformer(DEFAULT_MODEL)
    yield
    STATE.clear()


app = FastAPI(
    title="Alzheimer's research papers - RAG API",
    description="Answers questions using only 19 Alzheimer's disease research papers, "
                "with the passages it used as citations.",
    version="1.0.0",
    lifespan=lifespan,
)


# ----------------------------------------------------------------------------- schemas
Mode = Literal["vector", "keyword", "hybrid"]


class AskRequest(BaseModel):
    question: str = Field(..., min_length=3, max_length=1000,
                          description="e.g. Which variants' effects depend on APOE e4?")
    top_k: int = Field(5, ge=1, le=20, description="number of passages given to the LLM")
    retrieval: Optional[Mode] = Field(None, description="vector, keyword or hybrid "
                                                        "(default: the server's RETRIEVAL setting)")


class Source(BaseModel):
    n: int = Field(..., description="the number used in the answer's [n] citations")
    chunk_id: str
    title: str
    year: str
    section: str
    page_start: int
    page_end: int
    score: float = Field(..., description="depends on the search mode (cosine, ts_rank or RRF): "
                                          "only the ranking is meaningful")
    cited: bool = Field(..., description="the answer cites this source")


class AskResponse(BaseModel):
    question: str
    answer: str
    not_found: bool = Field(..., description="the model said the papers don't contain the answer")
    sources: List[Source]
    llm_model: str
    retrieval: str
    seconds: Dict[str, float]


class Chunk(BaseModel):
    rank: int
    chunk_id: str
    title: str
    year: str
    section: str
    page_start: int
    page_end: int
    score: float
    text: str


# ----------------------------------------------------------------------------- helpers
def _connect():
    try:
        conn = psycopg.connect(DSN, connect_timeout=5)
    except psycopg.OperationalError as e:
        raise HTTPException(503, "database unavailable: {}".format(str(e).splitlines()[0]))
    register_vector(conn)
    return conn


# ----------------------------------------------------------------------------- endpoints
@app.get("/health")
def health():
    with _connect() as conn:
        n_chunks, n_papers = conn.execute(
            "SELECT count(*), count(DISTINCT doc_id) FROM chunks").fetchone()
    return {"status": "ok", "papers": n_papers, "chunks": n_chunks,
            "embedding_model": DEFAULT_MODEL, "retrieval": default_mode(),
            "llm_base_url": answer.LLM_BASE_URL, "llm_model": answer.LLM_MODEL or "(auto)"}


@app.get("/search", response_model=List[Chunk])
def search_endpoint(q: str = Query(..., min_length=3, max_length=1000),
                    k: int = Query(5, ge=1, le=50),
                    mode: Optional[Mode] = Query(None, description="vector, keyword or hybrid"),
                    _caller: str = Depends(auth.require("search"))):
    with _connect() as conn:
        rows = search(q, STATE["embed_model"], conn, k, mode)
    return [Chunk(rank=i, chunk_id=r[0], title=r[1], year=r[2] or "", section=r[3] or "",
                  page_start=r[4], page_end=r[5], text=r[6], score=round(float(r[7]), 4))
            for i, r in enumerate(rows, start=1)]


@app.post("/ask", response_model=AskResponse)
def ask_endpoint(req: AskRequest, _caller: str = Depends(auth.require("ask"))):
    with _connect() as conn:
        try:
            result = answer.ask(req.question, conn, STATE["embed_model"], req.top_k, None, req.retrieval)
        except answer.LLMError as e:
            raise HTTPException(502, "LLM backend error: {}".format(e))
    cited = set(result["cited"])
    return AskResponse(
        question=result["question"], answer=result["answer"], not_found=result["not_found"],
        llm_model=result["llm_model"], retrieval=result["retrieval"], seconds=result["seconds"],
        sources=[Source(cited=s["n"] in cited, year=s["year"] or "", section=s["section"] or "",
                        **{k: v for k, v in s.items() if k not in ("year", "section")})
                 for s in result["sources"]],
    )
